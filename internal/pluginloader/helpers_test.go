// Test helpers shared across the pluginloader test files.

func neverExpires() time.Time { return time.Time{} }

func testCallTimeout() time.Duration { return 5 * time.Second }

func testCtx(t *testing.T) context.Context {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	t.Cleanup(cancel)
	return ctx
}

// minimalPluginBytes is a hand-built WASM module that exports the mandatory
// entry points (wasm_init, on_hook, on_request) plus the optional on_task
// entry point. All functions return i32 0 immediately. It is used by tests
// that need a loadable plugin without building the full Rust example.
//
// Type section:
//   t0 (i64) -> i32
//   t1 (i64, i64) -> i32
//   t2 (i64, i64, i64) -> i32
// Function section: [t0, t1, t2, t1]
// Exports: memory, wasm_init(0), on_hook(1), on_request(2), on_task(3)
var minimalPluginBytes = []byte{
	// WASM magic + version
	0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,

	// Type section (id=1, size=19)
	0x01, 0x13,
	0x03, // 3 types
	// t0: (i64) -> i32
	0x60, 0x01, 0x7e, 0x01, 0x7f,
	// t1: (i64, i64) -> i32
	0x60, 0x02, 0x7e, 0x7e, 0x01, 0x7f,
	// t2: (i64, i64, i64) -> i32
	0x60, 0x03, 0x7e, 0x7e, 0x7e, 0x01, 0x7f,

	// Function section (id=3, size=5)
	0x03, 0x05,
	0x04, 0x00, 0x01, 0x02, 0x01,

	// Memory section (id=5, size=3)
	0x05, 0x03,
	0x01, 0x00, 0x01,

	// Export section (id=7, size=55)
	0x07, 0x37,
	0x05, // 5 exports
	// "memory"
	0x06, 0x6d, 0x65, 0x6d, 0x6f, 0x72, 0x79, 0x02, 0x00,
	// "wasm_init"
	0x09, 0x77, 0x61, 0x73, 0x6d, 0x5f, 0x69, 0x6e, 0x69, 0x74, 0x00, 0x00,
	// "on_hook"
	0x07, 0x6f, 0x6e, 0x5f, 0x68, 0x6f, 0x6f, 0x6b, 0x00, 0x01,
	// "on_request"
	0x0a, 0x6f, 0x6e, 0x5f, 0x72, 0x65, 0x71, 0x75, 0x65, 0x73, 0x74, 0x00, 0x02,
	// "on_task"
	0x07, 0x6f, 0x6e, 0x5f, 0x74, 0x61, 0x73, 0x6b, 0x00, 0x03,

	// Code section (id=10, size=21)
	0x0a, 0x15,
	0x04, // 4 function bodies
	// body for wasm_init: size=4, locals=0, i32.const 0, end
	0x04, 0x00, 0x41, 0x00, 0x0b,
	// body for on_hook
	0x04, 0x00, 0x41, 0x00, 0x0b,
	// body for on_request
	0x04, 0x00, 0x41, 0x00, 0x0b,
	// body for on_task
	0x04, 0x00, 0x41, 0x00, 0x0b,
}
